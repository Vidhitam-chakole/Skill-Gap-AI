const formatConceptName = (concept) => {
  if (!concept) return 'Core Concept';
  const lower = concept.toLowerCase().trim();
  if (STUDENT_CONCEPT_NAMES[lower]) {
    return STUDENT_CONCEPT_NAMES[lower];
  }
  return concept
    .replace(/\s*&\s*scoping traps?/gi, '')
    .replace(/\s*traps?/gi, '')
    .replace(/forensic\s*/gi, '')
    .trim();
};

const formatVerdictTitle = (label) => {
  if (!label) return 'Assessment Complete';
  const lower = label.toLowerCase();
  if (lower.includes('suspect') || lower.includes('gap') || lower.includes('unverified')) {
    return 'Needs Practice / Fundamentals Review';
  }
  if (lower.includes('augmented') || lower.includes('developing')) {
    return 'Developing / Practice Recommended';
  }
  if (lower.includes('verified') || lower.includes('strong')) {
    return 'Strong Proficiency Verified';
  }
  return label.replace(/suspect ai-generated code\s*\/?\s*/gi, '').replace(/forensic/gi, '').trim();
};

const formatSummary = (summary, res) => {
  if (!summary) return '';
  const score = res?.score ?? 0;
  const total = res?.totalQuestions ?? 10;
  const pct = res?.percentage ?? 0;
  const lang = res?.language ?? 'code';

  if (
    summary.includes('strongly indicates that the code on your GitHub was generated by AI') ||
    summary.includes('without conceptual understanding') ||
    summary.includes('critical gaps in fundamental mechanics')
  ) {
    return `Score: ${score}/${total} (${pct}%). Key areas for review in ${lang} fundamentals. Reviewing the core topics below will help solidify these concepts.`;
  }
  return summary
    .replace(/forensic/gi, '')
    .replace(/AI copy-pasters?/gi, 'beginners')
    .replace(/AI prompt-copiers?/gi, 'learners')
    .trim();
};

const formatInsight = (insight) => {
  if (!insight) return 'Focus on core programming fundamentals and concepts to build confidence.';
  if (
    insight.includes('Modern recruiters and technical interviewers instantly spot this mismatch') ||
    insight.includes('pointer arithmetic')
  ) {
    return 'Focus on understanding core language behavior, variable lifecycles, and data structures to build solid mastery.';
  }
  return insight
    .replace(/forensic breakdown/gi, 'review')
    .replace(/forensic/gi, '')
    .replace(/\b(?:trap theory|scoping trap|compiler trap|trap)\b/gi, 'concept')
    .replace(/AI copy-pasting/gi, 'memorization')
    .trim();
};

const formatRecommendation = (rec) => {
  if (!rec) return '';
  if (rec.includes('whiteboard or plain text editor without AI auto-complete')) {
    return 'Practice writing and tracing code step-by-step to build problem-solving intuition.';
  }
  if (rec.includes('Do not claim') && rec.includes('Strong Language')) {
    return 'Review foundational syntax and core mechanics before technical interviews.';
  }
  if (rec.includes('Dedicate 2 weeks')) {
    return 'Spend time practicing data structures, execution flow, and core language rules.';
  }
  return rec
    .replace(/without AI auto-complete/gi, 'carefully')
    .replace(/forensic/gi, '')
    .trim();
};

const formatShortQuestion = (q) => {
  if (!q) return '';
  let clean = q.replace(/```[\s\S]*?```/g, '').replace(/`.*?`/g, '').trim();
  if (clean.includes('\n')) {
    clean = clean.split('\n')[0].trim();
  }
  const sentences = clean.split(/(?<=[.?!])\s+/);
  if (sentences.length > 0 && sentences[0].length >= 15) {
    clean = sentences[0];
  }
  if (clean.length > 105) {
    return clean.slice(0, 102).trim() + '...';
  }
  return clean;
};

const formatExplanation = (text) => {
  if (!text) return '';
  return text
    .replace(/\b(?:trap theory|scoping trap|compiler trap|trap)\b/gi, 'concept')
    .replace(/\b(?:traps)\b/gi, 'pitfalls')
    .replace(/\s*AI copy-pasters often [^.]*\./gi, '')
    .replace(/\s*A classic differentiator between [^.]*\./gi, '')
    .replace(/\s*AI prompt-copiers[^.]*\./gi, '')
    .replace(/\s*AI-prompted coders[^.]*\./gi, '')
    .replace(/\s*AI hallucination[^.]*\./gi, '')
    .replace(/forensic/gi, '')
    .trim();
};

export default function SkillVerifier({ initialLanguage = null }) {
  const { linkedinResult, githubResult, verifierTargetLang } = useAnalysis();
  const effectiveInitial = initialLanguage || verifierTargetLang;
  const [selectedLanguage, setSelectedLanguage] = useState(effectiveInitial || 'HTML');
  const [quiz, setQuiz] = useState(null);
  const [currentIndex, setCurrentIndex] = useState(0);
  const [answers, setAnswers] = useState({});
  const [loading, setLoading] = useState(false);
  const [submitting, setSubmitting] = useState(false);
  const [error, setError] = useState(null);
  const [results, setResults] = useState(null);
  const [startTime, setStartTime] = useState(null);

  const strongestLang =
    effectiveInitial ||
    githubResult?.topLanguages?.[0]?.name ||
    githubResult?.primaryLanguage ||
    'HTML';

  const strongestPct =
    githubResult?.topLanguages?.find((l) => (l.name || '').toLowerCase() === (strongestLang || '').toLowerCase())?.percentage ||
    githubResult?.topLanguages?.[0]?.percentage;

  // All detected languages from GitHub or clean defaults
  const allLanguages = (githubResult?.topLanguages && githubResult.topLanguages.length > 0)
    ? githubResult.topLanguages
    : [
        { name: 'HTML' },
        { name: 'JavaScript' },
        { name: 'C' },
        { name: 'Python' },
      ];

  // Start Assessment
  const handleStartQuiz = async (langToUse = selectedLanguage) => {
    setLoading(true);
    setError(null);
    setResults(null);
    setAnswers({});
    setCurrentIndex(0);

    try {
      const data = await skillVerifierApi.generate(
        langToUse,
        githubResult?.analysisId || null
      );
      setQuiz(data);
      setStartTime(Date.now());
    } catch (err) {
      setError(err.message || 'Failed to generate assessment. Please try again.');
    } finally {
      setLoading(false);
    }
  };

  // Sync selected language and auto-start if triggered from Start Test button
  useEffect(() => {
    const target = verifierTargetLang || initialLanguage;
    if (target) {
      setSelectedLanguage(target);
      handleStartQuiz(target);
    } else if (strongestLang) {
      setSelectedLanguage(strongestLang);
    } else if (allLanguages[0]?.name) {
      setSelectedLanguage(allLanguages[0].name);
    }
  }, [verifierTargetLang, initialLanguage]);

  const handleSelectOption = (questionId, optionIndex) => {
    setAnswers((prev) => ({
      ...prev,
      [questionId]: optionIndex,
    }));
  };

  const handleSubmit = async () => {
    if (!quiz) return;
    setSubmitting(true);
    setError(null);

    const timeSpent = startTime ? Math.round((Date.now() - startTime) / 1000) : 0;

    try {
      const evalResult = await skillVerifierApi.submit({
        quizId: quiz.quizId,
        language: quiz.language,
        answers,
        timeSpentSeconds: timeSpent,
      });
      setResults(evalResult);
      setQuiz(null);
    } catch (err) {
      setError(err.message || 'Assessment submission failed.');
    } finally {
      setSubmitting(false);
    }
  };

  const currentQ = quiz?.questions?.[currentIndex];
  const totalQ = quiz?.questions?.length || 10;
  const answeredCount = Object.keys(answers).length;

  const getDifficultyClass = (diff) => {
    const d = (diff || '').toLowerCase();
    if (d.includes('fund')) return 'verifier__badge-diff--fundamental';
    if (d.includes('inter')) return 'verifier__badge-diff--intermediate';
    return 'verifier__badge-diff--deep-mechanics';
  };

  const getVerdictTheme = (status) => {
    if (status === 'VERIFIED_AUTHENTIC') return 'verifier__score-banner--verified';
    if (status === 'LIKELY_AI_AUGMENTED') return 'verifier__score-banner--augmented';
    return 'verifier__score-banner--suspect';
  };

  // Other detected languages from GitHub excluding the primary one
  const otherLanguages = (githubResult?.topLanguages || []).filter(
    (l) => l.name && l.name.toLowerCase() !== (strongestLang || '').toLowerCase()
  );

  return (
    <section id="verifier" className="verifier">
      <Sticker color="yellow" rotation={3} className="verifier__sticker">AI Skill Verifier &amp; Assessment</Sticker>

      <SectionHeader
        title="AI Skill Verifier &amp; Technical Coding Assessment"
        subtitle="Interactive coding challenges to verify technical skills, benchmark programming proficiency, and validate competencies for software developer jobs."
        rotate={1}
      />

      {error && <div className="analyzer__error" style={{ marginBottom: '1.5rem' }}>{error}</div>}

      {/* 1. SETUP / LANGUAGE SELECTOR VIEW */}
      {!quiz && !results && (
        <div className="verifier__setup-card brutal-card reveal">
          {/* Connected Profiles Badges */}
          {(githubResult || linkedinResult) && (
            <div className="verifier__connected-strip">
              {githubResult && (
                <div className="verifier__connected-pill verifier__connected-pill--github">
                  <span className="verifier__pulse-dot"></span>
                  <span>GITHUB: @{githubResult.username}</span>
                </div>
              )}
              {linkedinResult && (
                <div className="verifier__connected-pill verifier__connected-pill--linkedin">
                  <span>✓ LINKEDIN: {linkedinResult.name}</span>
                </div>
              )}
            </div>
          )}

          <div className="verifier__start-section">
            <button
              type="button"
              className="brutal-btn brutal-btn--accent verifier__start-btn"
              disabled={loading}
              onClick={() => handleStartQuiz(selectedLanguage || allLanguages[0]?.name)}
            >
              {loading ? 'Preparing...' : 'Start'}
            </button>

            <div className="verifier__lang-selector">
              <span className="verifier__lang-label">Languages:</span>
              <div className="verifier__lang-pills">
                {allLanguages.map((lang, idx) => {
                  const currentSelected = selectedLanguage || allLanguages[0]?.name;
                  const isSelected = currentSelected.toLowerCase() === lang.name.toLowerCase();
                  return (
                    <button
                      key={idx}
                      type="button"
                      className={`verifier__lang-pill ${isSelected ? 'verifier__lang-pill--active' : ''}`}
                      onClick={() => setSelectedLanguage(lang.name)}
                    >
                      {lang.name}
                      {lang.percentage ? <span className="verifier__lang-pill-pct"> ({lang.percentage}%)</span> : null}
                    </button>
                  );
                })}
              </div>
            </div>
          </div>
        </div>
      )}

      {/* 2. ACTIVE QUIZ VIEW */}
      {quiz && currentQ && (
        <div className="verifier__quiz-card brutal-card">
          {/* Progress bar */}
          <div className="verifier__progress-bar-wrap">
            <div
              className="verifier__progress-bar-fill"
              style={{ width: `${((currentIndex + 1) / totalQ) * 100}%` }}
            />
          </div>

          {/* Header */}
          <div className="verifier__quiz-header">
            <div className="verifier__q-num">
              Question {currentIndex + 1} of {totalQ}
            </div>
            <div className="verifier__q-meta">
              <span className={`verifier__badge-diff ${getDifficultyClass(currentQ.difficulty)}`}>
                {currentQ.difficulty}
              </span>
              <span className="verifier__concept-tag">{currentQ.concept}</span>
              <span className="verifier__badge-dynamic">
                ✨ Dynamic Custom Paper ({quiz.language})
              </span>
            </div>
          </div>

          {/* Developer Context & Re-roll header */}
          <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', marginBottom: '1.25rem', fontSize: '0.9rem', color: '#334155', fontWeight: 600 }}>
            <span>
              {quiz.developerContext ? (
                <>Assessment calibrated for <strong>{quiz.developerContext}</strong></>
              ) : (
                <>Dynamic language evaluation</>
              )}
            </span>
            <button
              type="button"
              onClick={() => handleStartQuiz(quiz.language)}
              style={{ background: 'transparent', border: 'none', color: '#ff6b1a', cursor: 'pointer', fontSize: '0.85rem', fontWeight: 800, textDecoration: 'underline' }}
              title="Generate new questions for this language"
            >
              🎲 Re-roll Questions &rarr;
            </button>
          </div>

          {/* Question Text */}
          <div className="verifier__question-text">{currentQ.question}</div>

          {/* Code Snippet if present */}
          {currentQ.codeSnippet && (
            <div className="verifier__code-box">
              <pre>{currentQ.codeSnippet}</pre>
            </div>
          )}

          {/* Options Grid */}
          <div className="verifier__options-grid">
            {currentQ.options.map((opt, i) => {
              const isSelected = answers[currentQ.id] === opt.id;
              const letter = String.fromCharCode(65 + i); // A, B, C, D
              return (
                <button
                  key={opt.id}
                  type="button"
                  className={`verifier__option-btn ${isSelected ? 'verifier__option-btn--selected' : ''}`}
                  onClick={() => handleSelectOption(currentQ.id, opt.id)}
                >
                  <span className="verifier__opt-letter">{letter}</span>
                  <span>{opt.text}</span>
                </button>
              );
            })}
          </div>

          {/* Navigation Controls */}
          <div className="verifier__nav-controls">
            <button
              type="button"
              className="brutal-btn brutal-btn--outline"
              disabled={currentIndex === 0}
              onClick={() => setCurrentIndex((prev) => Math.max(0, prev - 1))}
            >
              &larr; Previous
            </button>

            {/* Jump Dots */}
            <div className="verifier__dots">
              {quiz.questions.map((q, idx) => {
                const isAnswered = answers[q.id] !== undefined;
                const isCurrent = idx === currentIndex;
                return (
                  <button
                    key={q.id}
                    type="button"
                    className={`verifier__dot ${isAnswered ? 'verifier__dot--answered' : ''} ${isCurrent ? 'verifier__dot--current' : ''}`}
                    onClick={() => setCurrentIndex(idx)}
                    title={`Question ${idx + 1}`}
                  >
                    {idx + 1}
                  </button>
                );
              })}
            </div>

            {currentIndex < totalQ - 1 ? (
              <button
                type="button"
                className="brutal-btn brutal-btn--primary"
                onClick={() => setCurrentIndex((prev) => Math.min(totalQ - 1, prev + 1))}
              >
                Next &rarr;
              </button>
            ) : (
              <button
                type="button"
                className="brutal-btn brutal-btn--accent"
                disabled={submitting}
                onClick={handleSubmit}
              >
                {submitting ? 'Verifying Answers...' : `Submit (${answeredCount}/${totalQ} Answered)`}
              </button>
            )}
          </div>
        </div>
      )}

      {/* 3. EVALUATION RESULTS VIEW */}
      {results && (
        <div className="verifier__results-card brutal-card">
          {/* Big Score Banner */}
          <div className={`verifier__score-banner ${getVerdictTheme(results.authenticityStatus)}`}>
            <div className="verifier__score-details">
              <span className="verifier__badge-pill">{results.badge}</span>
              <h2 className="verifier__verdict-title">{formatVerdictTitle(results.authenticityLabel)}</h2>
              <p style={{ lineHeight: '1.6', fontWeight: 600 }}>{formatSummary(results.summary, results)}</p>
            </div>
            <div className="verifier__score-dial">
              <span className="verifier__score-digits">
                {results.score}/{results.totalQuestions}
              </span>
              <span className="verifier__score-sub">{results.percentage}% Score</span>
            </div>
          </div>

          <div className="verifier__results-grid">
            {/* Key Insights & Suggestions */}
            <div className="verifier__card-block">
              <h3>
                <span>💡</span> Key Insights &amp; Suggestions
              </h3>
              <div className="verifier__insight-box">{formatInsight(results.aiDetectionInsight)}</div>
              <ul className="verifier__rec-list">
                {results.recommendations.map((rec, i) => (
                  <li key={i} className="verifier__rec-item">
                    {formatRecommendation(rec)}
                  </li>
                ))}
              </ul>
            </div>

            {/* Core Topics Tested */}
            <div className="verifier__card-block">
              <h3>
                <span>📊</span> Core Topics Tested
              </h3>
              <div className="verifier__concepts-list">
                {results.conceptBreakdown.map((c, i) => (
                  <div key={i} className="verifier__concept-item">
                    <div className="verifier__concept-meta">
                      <span>{formatConceptName(c.concept)}</span>
                      <span>
                        {c.correct}/{c.total} ({c.percentage}%)
                      </span>
                    </div>
                    <div className="verifier__concept-track">
                      <div
                        className="verifier__concept-fill"
                        style={{
                          width: `${c.percentage}%`,
                          backgroundColor:
                            c.percentage >= 80 ? '#16a34a' : c.percentage >= 50 ? '#ffaa00' : '#e11d48',
                        }}
                      />
                    </div>
                  </div>
                ))}
              </div>
            </div>
          </div>

          {/* Detailed Question Review */}
          <div className="verifier__review-section">
            <h3 className="verifier__review-title">Question Review &amp; Explanations</h3>
            <div className="verifier__review-list">
              {results.detailedReview.map((rev) => (
                <div
                  key={rev.id}
                  className={`verifier__review-item ${rev.isCorrect ? 'verifier__review-item--correct' : 'verifier__review-item--incorrect'}`}
                >
                  <div className="verifier__review-header">
                    <span className="verifier__concept-tag">Q{rev.id}: {formatConceptName(rev.concept)}</span>
                    <span
                      className={`verifier__review-status ${rev.isCorrect ? 'verifier__review-status--ok' : 'verifier__review-status--bad'}`}
                    >
                      {rev.isCorrect ? '✓ Correct' : '✗ Incorrect'}
                    </span>
                  </div>

                  <p style={{ fontWeight: 800, color: 'var(--black, #0a0a0a)', marginBottom: '0.75rem', fontSize: '1.05rem' }}>
                    {formatShortQuestion(rev.question)}
                  </p>

                  <div style={{ fontSize: '0.95rem', color: '#1e293b', marginBottom: '0.5rem', fontWeight: 600 }}>
                    <div>
                      <strong>Your Answer: </strong>
                      <span style={{ color: rev.isCorrect ? '#16a34a' : '#e11d48', fontWeight: 800 }}>
                        {rev.selectedIndex !== null && rev.selectedIndex !== undefined
                          ? `${String.fromCharCode(65 + rev.selectedIndex)}: ${rev.options[rev.selectedIndex]}`
                          : 'No answer selected'}
                      </span>
                    </div>
                    {!rev.isCorrect && (
                      <div style={{ marginTop: '0.35rem' }}>
                        <strong>Correct Answer: </strong>
                        <span style={{ color: '#16a34a', fontWeight: 800 }}>
                          {String.fromCharCode(65 + rev.correctIndex)}: {rev.options[rev.correctIndex]}
                        </span>
                      </div>
                    )}
                  </div>

                  <div className="verifier__explanation-box">
                    <strong>Explanation:</strong>
                    {formatExplanation(rev.explanation)}
                  </div>
                </div>
              ))}
            </div>
          </div>

          {/* Actions Footer */}
          <div className="verifier__actions-footer">
            <button
              type="button"
              className="brutal-btn brutal-btn--primary"
              onClick={() => handleStartQuiz(results.language)}
            >
              🎲 Retake {results.language} Assessment
            </button>
            <button
              type="button"
              className="brutal-btn brutal-btn--outline"
              onClick={() => {
                setResults(null);
                setQuiz(null);
              }}
            >
              Verify Another Language
            </button>
            <a href="#chat" className="brutal-btn brutal-btn--accent">
              Ask AI Career Assistant About These Gaps &rarr;
            </a>
          </div>

          {/* Quick links to test remaining GitHub languages */}
          {otherLanguages.length > 0 && (
            <div style={{ marginTop: '1.75rem', paddingTop: '1.5rem', borderTop: '2px dashed var(--black, #0a0a0a)' }}>
              <span style={{ fontSize: '0.85rem', color: 'var(--black, #0a0a0a)', textTransform: 'uppercase', fontWeight: 800, display: 'block', marginBottom: '0.75rem' }}>
                Test other languages:
              </span>
              <div className="verifier__gh-chips">
                {otherLanguages
                  .filter((l) => l.name.toLowerCase() !== results.language.toLowerCase())
                  .map((lang, idx) => (
                    <button
                      key={idx}
                      type="button"
                      className="verifier__chip"
                      onClick={() => {
                        setSelectedLanguage(lang.name);
                        handleStartQuiz(lang.name);
                      }}
                    >
                      {lang.name} {lang.percentage ? `(${lang.percentage}%)` : ''}
                    </button>
                  ))}
              </div>
            </div>
          )}
        </div>
      )}
    </section>
  );
}
